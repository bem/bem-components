import { readdirSync, existsSync, statSync } from 'node:fs';
import { join, resolve, relative, basename } from 'node:path';

const I18N_PREFIX = 'bem:i18n';
const VIRTUAL_I18N = '\0bem:i18n';

/**
 * Scans BEM levels for .i18n/ directories and collects keyset files.
 *
 * Each .i18n/ directory contains per-language keyset files:
 *   common.blocks/attach/attach.i18n/ru.js → keyset "attach", lang "ru"
 *   common.blocks/attach/attach.i18n/en.js → keyset "attach", lang "en"
 *
 * @param {string[]} levels - level directory paths
 * @param {string} rootDir - project root
 * @returns {Map<string, Map<string, string>>} lang → Map<keysetName, filePath>
 */
function scanI18nKeysets(levels, rootDir) {
    /** @type {Map<string, Map<string, string>>} */
    const langMap = new Map();

    for (const level of levels) {
        const levelDir = resolve(rootDir, level);
        if (!existsSync(levelDir)) continue;

        let blocks;
        try {
            blocks = readdirSync(levelDir);
        } catch {
            continue;
        }

        for (const block of blocks) {
            const blockDir = join(levelDir, block);
            if (!statSync(blockDir).isDirectory()) continue;

            // Look for <block>.i18n/ directory
            const i18nDir = join(blockDir, block + '.i18n');
            if (!existsSync(i18nDir) || !statSync(i18nDir).isDirectory()) continue;

            // Scan language files
            let langFiles;
            try {
                langFiles = readdirSync(i18nDir);
            } catch {
                continue;
            }

            for (const langFile of langFiles) {
                if (!langFile.endsWith('.js')) continue;
                const lang = basename(langFile, '.js');
                const filePath = join(i18nDir, langFile);

                if (!langMap.has(lang)) {
                    langMap.set(lang, new Map());
                }
                langMap.get(lang).set(block, filePath);
            }
        }
    }

    return langMap;
}

/**
 * Generates a virtual i18n module that imports all keyset files for a given
 * language, merges them, and exports a lookup function.
 *
 * Usage in blocks:
 *   import i18n from 'bem:i18n';
 *   const text = i18n('attach', 'button-text'); // → "Choose file"
 *
 * @param {Map<string, string>} keysets - keysetName → filePath
 * @param {string} rootDir - project root
 * @returns {string} generated ES module source
 */
function generateI18nModule(keysets, rootDir) {
    const lines = ['// @generated by vite-plugin-bem-i18n'];
    const imports = [];
    let idx = 0;

    for (const [, filePath] of keysets) {
        const id = `_keyset${idx++}`;
        const relPath = './' + relative(rootDir, filePath).replace(/\\/g, '/');
        lines.push(`import ${id} from '${relPath}';`);
        imports.push(id);
    }

    lines.push('');
    lines.push('// Merge all keysets into a single data object');
    lines.push('const _data = {};');
    for (const id of imports) {
        lines.push(`for (const [ks, keys] of Object.entries(${id})) {`);
        lines.push(`    if (!_data[ks]) _data[ks] = {};`);
        lines.push(`    Object.assign(_data[ks], keys);`);
        lines.push(`}`);
    }

    lines.push('');
    lines.push('/**');
    lines.push(' * Look up a translated string by keyset and key.');
    lines.push(' * @param {string} keyset');
    lines.push(' * @param {string} key');
    lines.push(' * @param {Object} [params]');
    lines.push(' * @returns {string}');
    lines.push(' */');
    lines.push('function i18n(keyset, key, params) {');
    lines.push('    const val = _data[keyset] && _data[keyset][key];');
    lines.push('    if (typeof val === \'undefined\') return keyset + \':\' + key;');
    lines.push('    if (typeof val === \'string\') return val;');
    lines.push('    return val.call(i18n, params, i18n);');
    lines.push('}');
    lines.push('');
    lines.push('/**');
    lines.push(' * Register additional keyset data at runtime.');
    lines.push(' * @param {Object} i18nData');
    lines.push(' */');
    lines.push('i18n.decl = function(i18nData) {');
    lines.push('    for (const ks in i18nData) {');
    lines.push('        if (!_data[ks]) _data[ks] = {};');
    lines.push('        Object.assign(_data[ks], i18nData[ks]);');
    lines.push('    }');
    lines.push('    return i18n;');
    lines.push('};');
    lines.push('');
    lines.push('export default i18n;');

    return lines.join('\n');
}

/**
 * Vite plugin for BEM i18n keyset integration.
 *
 * Scans .i18n/ directories in BEM levels, generates a virtual `bem:i18n`
 * module that merges all keysets for the selected language and exports
 * an i18n(keyset, key) lookup function.
 *
 * @param {object} options
 * @param {string} options.lang - language code (default: from BEM_LANG env or 'ru')
 * @param {string} options.platform - 'desktop', 'touch-pad', or 'touch-phone'
 * @param {object} options.levels - platform → level directories mapping
 * @param {string} [options.rootDir] - project root (default: process.cwd())
 */
export default function bemI18n(options = {}) {
    const {
        lang = process.env.BEM_LANG || 'ru',
        platform = 'desktop',
        levels = {},
        rootDir = process.cwd(),
    } = options;

    const platformLevels = levels[platform];
    if (!platformLevels) {
        throw new Error(
            `vite-plugin-bem-i18n: unknown platform "${platform}". ` +
            `Available: ${Object.keys(levels).join(', ')}`
        );
    }

    let keysetMap = null;

    function getKeysets() {
        if (!keysetMap) {
            keysetMap = scanI18nKeysets(platformLevels, rootDir);
        }
        return keysetMap;
    }

    return {
        name: 'vite-plugin-bem-i18n',

        resolveId(id) {
            if (id === I18N_PREFIX) {
                return VIRTUAL_I18N;
            }
            return null;
        },

        load(id) {
            if (id !== VIRTUAL_I18N) return null;

            const allKeysets = getKeysets();
            const langKeysets = allKeysets.get(lang);

            if (!langKeysets || langKeysets.size === 0) {
                // No keysets for this language — return a stub
                this.warn(
                    `No i18n keysets found for lang "${lang}". ` +
                    `Available: ${[...allKeysets.keys()].join(', ') || 'none'}`
                );
                return [
                    '// @generated by vite-plugin-bem-i18n — no keysets found',
                    'function i18n(keyset, key) { return keyset + ":" + key; }',
                    'i18n.decl = function() { return i18n; };',
                    'export default i18n;',
                ].join('\n');
            }

            return generateI18nModule(langKeysets, rootDir);
        },

        // Invalidate cache on changes to .i18n/ directories
        configureServer(server) {
            const levelDirs = platformLevels.map(l => resolve(rootDir, l));
            server.watcher.on('all', (event, filePath) => {
                if (!filePath.includes('.i18n/')) return;
                for (const levelDir of levelDirs) {
                    if (filePath.startsWith(levelDir)) {
                        keysetMap = null;
                        break;
                    }
                }
            });
        },

        // Expose internals for testing
        api: {
            getKeysets() { return getKeysets(); },
            scanI18nKeysets,
            generateI18nModule,
        },
    };
}

export { scanI18nKeysets, generateI18nModule };
